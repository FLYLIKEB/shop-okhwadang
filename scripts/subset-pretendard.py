#!/usr/bin/env python3
"""Rebuild local subsets: pip install 'fonttools[woff]==4.61.1'.

Original WOFF2 files remain the source of truth. All cmap codepoints are retained;
common KS X 1001 Hangul uses one file, uncommon characters use bounded blocks.
"""
from pathlib import Path
from copy import deepcopy
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'public/fonts/pretendard'
OUT = FONTS / 'subsets'
OUT.mkdir(exist_ok=True)


def common_hangul(cp):
    if not 0xAC00 <= cp <= 0xD7A3:
        return False
    return len(chr(cp).encode('euc_kr')) == 2


def ranges(points):
    groups = []
    for cp in sorted(points):
        if groups and cp == groups[-1][1] + 1:
            groups[-1][1] = cp
        else:
            groups.append([cp, cp])
    return ','.join(f'U+{a:X}' + (f'-{b:X}' if a != b else '') for a, b in groups)


css = ['/* Generated by scripts/subset-pretendard.py; see fonts/pretendard/OFL.txt. */']
for face, weight in [('Bold', 700), ('SemiBold', 600), ('Medium', 500), ('Regular', 400)]:
    source = FONTS / f'Pretendard-{face}.woff2'
    original = TTFont(source)
    original.ensureDecompiled()
    points = set(original.getBestCmap())
    groups = {}
    for cp in sorted(points):
        group = 'latin' if cp < 0x300 else 'hangul-common' if common_hangul(cp) else f'{cp // 1024:03x}'
        groups.setdefault(group, set()).add(cp)
    covered = set()
    for group, chars in groups.items():
        font = deepcopy(original)
        options = subset.Options()
        options.recalc_timestamp = False
        options.flavor = 'woff2'
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=chars)
        worker.subset(font)
        # OFL reserved font names require a distinct name for modified fonts.
        for record in font['name'].names:
            if record.nameID in (1, 3, 4, 6, 16):
                name = f'OckhwadangSans-{face}' if record.nameID == 6 else f'Ockhwadang Sans {face}'
                record.string = name.encode(record.getEncoding())
        dest = OUT / f'OckhwadangSans-{face}-{group}.woff2'
        font.save(dest)
        actual = set(TTFont(dest).getBestCmap())
        assert actual == chars, (dest, actual ^ chars)
        assert not covered & actual
        covered.update(actual)
        css.append(f"@font-face{{font-family:Pretendard;font-style:normal;font-weight:{weight};font-display:swap;src:url('/fonts/pretendard/subsets/{dest.name}') format('woff2');unicode-range:{ranges(chars)}}}")
    assert covered == points
    common_bytes = sum((OUT / f'OckhwadangSans-{face}-{g}.woff2').stat().st_size for g in ['latin', 'hangul-common'])
    print(f'{face}: {len(points)} codepoints preserved, common Latin+Hangul {common_bytes:,} / {source.stat().st_size:,} bytes')
(ROOT / 'src/styles/pretendard-subsets.css').write_text('\n'.join(css) + '\n')
